-- Jalankan sekali di Supabase SQL Editor setelah backup schema.
-- Statistik pembaca untuk banner populer dan dashboard admin.
ALTER TABLE public.manga ADD COLUMN IF NOT EXISTS views bigint NOT NULL DEFAULT 0;

CREATE OR REPLACE FUNCTION public.increment_manga_views(target_manga_id uuid)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  UPDATE public.manga SET views = COALESCE(views, 0) + 1 WHERE id = target_manga_id;
$$;
GRANT EXECUTE ON FUNCTION public.increment_manga_views(uuid) TO anon, authenticated;

-- Komentar dan balasan per chapter. Pengunjung dapat membaca dan menulis komentar.
CREATE TABLE IF NOT EXISTS public.chapter_comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chapter_id uuid NOT NULL REFERENCES public.chapters(id) ON DELETE CASCADE,
  display_name text NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 40),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  parent_id bigint REFERENCES public.chapter_comments(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS chapter_comments_chapter_created_idx
  ON public.chapter_comments(chapter_id, created_at);
ALTER TABLE public.chapter_comments ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public can read chapter comments" ON public.chapter_comments;
CREATE POLICY "Public can read chapter comments" ON public.chapter_comments
  FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Public can post chapter comments" ON public.chapter_comments;
CREATE POLICY "Public can post chapter comments" ON public.chapter_comments
  FOR INSERT TO anon, authenticated WITH CHECK (
    char_length(trim(display_name)) BETWEEN 1 AND 40
    AND char_length(trim(body)) BETWEEN 1 AND 1000
    AND (parent_id IS NULL OR EXISTS (
      SELECT 1 FROM public.chapter_comments parent
      WHERE parent.id = parent_id AND parent.chapter_id = chapter_comments.chapter_id
    ))
  );
-- Anti-spam sederhana: tidak ada hak update/delete publik. Admin moderation bisa ditambahkan terpisah.
